use proc_macro::TokenStream;
use proc_macro2::{Span, TokenStream as TokenStream2};
use quote::quote;
use syn::{
    Data, DeriveInput, Expr, Fields, GenericParam, Token, Type, parse::ParseStream,
    parse_macro_input,
};

/// Derive [`Dimension`](::yadc::Dimension) for a named-field struct.
///
/// Numeric fields are interpreted as dimension exponents; any single field
/// annotated `#[kind]` carries a user-defined Kind enum.
///
/// Emitted for the struct:
/// - `impl ConstParamTy_ + StructuralPartialEq for Dim`
/// - `impl const PartialEq + Eq for Dim` - enables `==`/`!=` in const expressions.
/// - `impl const Mul + Div + Add + Sub for Dim` - dimensional arithmetic.
/// - `impl Dimension for Dim` - `ZERO`, `valid`, `numeric_eq`.
/// - Inherent const fns: `valid`, `numeric_eq`, `dims_eq` (value-based equality
///   for const generic expressions), `can_mul`, `can_div`, `can_add`, `can_sub`,
///   `can_add_assign`, `can_sub_assign`.
///
/// Users should add `#[derive(Debug)]` themselves - the derive no longer emits
/// one. `PartialEq` and `Eq` are generated by this derive and must not be
/// listed separately in `#[derive(...)]`.
///
/// ```ignore
/// #[derive(Copy, Clone, Debug, Dimension)]
/// pub struct Dim {
///     pub m: i8, pub kg: i8, pub s: i8,
///     #[kind] pub kind: Kind,
/// }
/// ```
#[proc_macro_derive(Dimension, attributes(kind))]
pub fn derive_dimension(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_dimension(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

/// Derive the dimensional **Kind** trait and combinator ops on an enum.
///
/// Variants are matched against a fixed set of *roles* by name (or via a
/// `#[kind(<Role>)]` override, e.g. `#[kind(Linear)] Scalar`). Recognized roles:
/// `Linear`, `Affine`, `Angle`, `SolidAngle`, `Logarithmic`, `LogarithmicAffine`,
/// `Invalid`. Only `Linear` and `Invalid` are **required**; declare just the
/// roles your system needs. Algebra arms naming an absent role are not emitted,
/// so those combinations fall through to `Invalid`.
///
/// Role semantics:
/// - `Linear` is the multiplicative/additive identity; `Invalid` is the sentinel.
/// - `Affine`/`Linear`: an absolute point minus an absolute point is a delta
///   (`Affine - Affine = Linear`), `Affine + Linear = Affine`.
/// - `Angle`/`SolidAngle`: `Angle * Angle = SolidAngle`, `SolidAngle / Angle = Angle`.
/// - `LogarithmicAffine`/`Logarithmic` mirror `Affine`/`Linear` on a log scale:
///   `LogarithmicAffine - LogarithmicAffine = Logarithmic`,
///   `LogarithmicAffine + Logarithmic = LogarithmicAffine`.
///
/// Emits:
/// - `impl ConstParamTy_ + StructuralPartialEq for Kind`
/// - `impl const PartialEq + Eq for Kind`
/// - `impl const Mul + Div + Add + Sub for Kind` - kind algebra tables.
/// - `impl yadc::traits::Kind for Kind` - the `ZERO` / `INVALID` consts.
///
/// The UCUM string mapping (`name` / `ucum_prefix` / `from_ucum_prefix`) is a
/// separate [`UcumKind`](macro@UcumKind) derive, gated behind serde.
#[proc_macro_derive(Kind, attributes(kind))]
pub fn derive_kind(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_kind(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

/// Derive [`UcumKind`](::yadc::traits::UcumKind) for a Kind enum - the UCUM
/// serialization mapping (`name`, `ucum_prefix`, `from_ucum_prefix`).
///
/// Kept separate from [`Kind`](macro@Kind) so the core algebra trait carries no
/// wire-format knowledge. Only [`UcumSerialize`](macro@UcumSerialize) /
/// [`UcumDeserialize`](macro@UcumDeserialize) call these, so derive it
/// under the same serde gate, e.g.
/// `#[cfg_attr(feature = "serde", derive(yadc::UcumKind))]`.
#[proc_macro_derive(UcumKind, attributes(kind))]
pub fn derive_ucum_kind(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_ucum_kind(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

const KIND_ROLES: [&str; 7] = [
    "Linear", "Affine", "Angle", "SolidAngle", "Logarithmic", "LogarithmicAffine", "Invalid",
];

// Parse a Kind enum: validate unit variants and map each to its role (by a
// `#[kind(<Role>)]` override or by variant name). Returns every variant ident
// (for `PartialEq` / `name`) and the role -> ident map. Shared by the `Kind`
// and `UcumKind` derives.
fn kind_roles(
    input: &DeriveInput,
) -> syn::Result<(Vec<&syn::Ident>, std::collections::HashMap<&'static str, &syn::Ident>)> {
    let name = &input.ident;
    let variants = match &input.data {
        Data::Enum(e) => &e.variants,
        _ => {
            return Err(syn::Error::new_spanned(
                name,
                "#[derive(Kind)] only works on enums",
            ));
        }
    };

    let mut role_map: std::collections::HashMap<&'static str, &syn::Ident> =
        std::collections::HashMap::new();
    for variant in variants {
        if !matches!(variant.fields, Fields::Unit) {
            return Err(syn::Error::new_spanned(
                variant,
                "#[derive(Kind)] variants must be unit variants",
            ));
        }
        // Look for a #[kind(RoleName)] override, else fall back to the variant name.
        let mut role: Option<&'static str> = None;
        for attr in &variant.attrs {
            if attr.path().is_ident("kind") {
                let arg: syn::Ident = attr.parse_args()?;
                let s = arg.to_string();
                let matched = KIND_ROLES.iter().find(|r| **r == s).ok_or_else(|| {
                    syn::Error::new_spanned(
                        &arg,
                        "kind role must be one of: Linear, Affine, Angle, SolidAngle, \
                         Logarithmic, LogarithmicAffine, Invalid",
                    )
                })?;
                role = Some(*matched);
                break;
            }
        }
        let role = role
            .or_else(|| {
                let n = variant.ident.to_string();
                KIND_ROLES.iter().find(|r| **r == n).copied()
            })
            .ok_or_else(|| {
                syn::Error::new_spanned(
                    variant,
                    format!(
                        "variant `{}` doesn't name a known kind role; add #[kind(<Role>)]",
                        variant.ident
                    ),
                )
            })?;
        if role_map.insert(role, &variant.ident).is_some() {
            return Err(syn::Error::new_spanned(
                variant,
                format!("duplicate kind role `{role}`"),
            ));
        }
    }

    let variant_idents = variants.iter().map(|v| &v.ident).collect();
    Ok((variant_idents, role_map))
}

// Generates ConstParamTy_, ZERO/INVALID, impl const PartialEq/Eq, and impl const
// Mul/Div/Add/Sub on an enum representing a dimensional "kind". Roles are matched
// by variant name (or a #[kind(<Role>)] override). Only Linear and Invalid are
// mandatory; arms for absent optional roles are skipped.
fn expand_kind(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let (variant_idents, role_map) = kind_roles(input)?;

    // Only `Linear` (the identity) and `Invalid` (the sentinel) are mandatory.
    // Every other role is optional; algebra arms referencing an absent role are
    // simply not emitted, so the combination falls through to `_ => Invalid`.
    let get = |r: &'static str| -> syn::Result<&syn::Ident> {
        role_map
            .get(r)
            .copied()
            .ok_or_else(|| syn::Error::new_spanned(name, format!("missing kind role `{r}`")))
    };
    let v_linear = get("Linear")?;
    let v_invalid = get("Invalid")?;
    let affine = role_map.get("Affine").copied();
    let angle = role_map.get("Angle").copied();
    let solid = role_map.get("SolidAngle").copied();
    let log = role_map.get("Logarithmic").copied(); // ratio/delta (mirrors Linear)
    let logaff = role_map.get("LogarithmicAffine").copied(); // absolute (mirrors Affine)

    // `variant_idents` (from `kind_roles`) drives the fully general `PartialEq`.

    // Algebra arms, assembled per-operator. Each arm is gated on the presence of
    // the roles it names; the trailing `_ => Invalid` makes every match total.
    let inv = quote! { #name::#v_invalid };
    let mut mul = Vec::new();
    let mut div = Vec::new();
    let mut add = Vec::new();
    let mut sub = Vec::new();

    // --- Mul -----------------------------------------------------------------
    mul.push(quote! { (#name::#v_invalid, _) | (_, #name::#v_invalid) => #inv, });
    if let Some(la) = logaff {
        // Absolute log levels never participate in Mul.
        mul.push(quote! { (#name::#la, _) | (_, #name::#la) => #inv, });
    }
    // Affine (absolute) values never multiply - not even by a dimensionless
    // (Linear) quantity, which would otherwise scale an absolute. Emitted before
    // the Linear-identity arm so affine never rides it.
    if let Some(af) = affine {
        mul.push(quote! { (#name::#af, _) | (_, #name::#af) => #inv, });
    }
    // Linear is the multiplicative identity.
    mul.push(quote! { (#name::#v_linear, k) | (k, #name::#v_linear) => k, });
    if let (Some(an), Some(so)) = (angle, solid) {
        mul.push(quote! { (#name::#an, #name::#an) => #name::#so, }); // rad^2 = sr
    }
    if let Some(so) = solid {
        mul.push(quote! { (#name::#so, #name::#so) => #name::#v_linear, });
    }
    mul.push(quote! { _ => #inv, });

    // --- Div -----------------------------------------------------------------
    div.push(quote! { (#name::#v_invalid, _) | (_, #name::#v_invalid) => #inv, });
    if let Some(la) = logaff {
        div.push(quote! { (#name::#la, _) | (_, #name::#la) => #inv, });
    }
    if let Some(lo) = log {
        // Logarithmic / Logarithmic = Linear (ratio of ratios); nothing else
        // can be divided by a log ratio.
        div.push(quote! { (#name::#lo, #name::#lo) => #name::#v_linear, });
        div.push(quote! { (_, #name::#lo) => #inv, });
    }
    // Affine (absolute) values don't divide, with one exception: an absolute
    // over an absolute of the same dim is a pure ratio (Linear) - this is how a
    // quantity is read back as a scalar (`q / one_base_unit`). Every other affine
    // division (e.g. affine / dimensionless) is rejected, so an absolute can't be
    // scaled. Emitted before the Linear-identity arm so affine never rides it.
    if let Some(af) = affine {
        div.push(quote! { (#name::#af, #name::#af) => #name::#v_linear, });
        div.push(quote! { (#name::#af, _) | (_, #name::#af) => #inv, });
    }
    // Linear denominator is the identity.
    div.push(quote! { (k, #name::#v_linear) => k, });
    if let Some(an) = angle {
        div.push(quote! { (#name::#an, #name::#an) => #name::#v_linear, });
    }
    if let (Some(so), Some(an)) = (solid, angle) {
        div.push(quote! { (#name::#so, #name::#an) => #name::#an, }); // sr / rad = rad
    }
    if let Some(so) = solid {
        div.push(quote! { (#name::#so, #name::#so) => #name::#v_linear, });
    }
    div.push(quote! { _ => #inv, });

    // --- Add -----------------------------------------------------------------
    // Logarithmic algebra mirrors Affine/Linear: an absolute level (LogAffine)
    // plus a ratio (Logarithmic) is an absolute level; level + level is invalid.
    add.push(quote! { (#name::#v_invalid, _) | (_, #name::#v_invalid) => #inv, });
    if let (Some(la), Some(lo)) = (logaff, log) {
        add.push(quote! { (#name::#la, #name::#lo) | (#name::#lo, #name::#la) => #name::#la, });
    }
    if let Some(lo) = log {
        add.push(quote! { (#name::#lo, #name::#lo) => #name::#lo, });
    }
    if let Some(la) = logaff {
        add.push(quote! { (#name::#la, _) | (_, #name::#la) => #inv, });
    }
    if let Some(lo) = log {
        add.push(quote! { (#name::#lo, _) | (_, #name::#lo) => #inv, });
    }
    add.push(quote! { (#name::#v_linear, #name::#v_linear) => #name::#v_linear, });
    if let Some(af) = affine {
        add.push(quote! {
            (#name::#af, #name::#v_linear) | (#name::#v_linear, #name::#af) => #name::#af,
        });
    }
    if let Some(an) = angle {
        add.push(quote! { (#name::#an, #name::#an) => #name::#an, });
    }
    if let Some(so) = solid {
        add.push(quote! { (#name::#so, #name::#so) => #name::#so, });
    }
    add.push(quote! { _ => #inv, });

    // --- Sub -----------------------------------------------------------------
    // LogAffine - LogAffine = Logarithmic (level - level = ratio); LogAffine -
    // Logarithmic = LogAffine (remove a ratio from a level). Mirrors Affine.
    sub.push(quote! { (#name::#v_invalid, _) | (_, #name::#v_invalid) => #inv, });
    if let (Some(la), Some(lo)) = (logaff, log) {
        sub.push(quote! { (#name::#la, #name::#la) => #name::#lo, });
        sub.push(quote! { (#name::#la, #name::#lo) => #name::#la, });
    }
    if let Some(lo) = log {
        sub.push(quote! { (#name::#lo, #name::#lo) => #name::#lo, });
    }
    if let Some(la) = logaff {
        sub.push(quote! { (#name::#la, _) | (_, #name::#la) => #inv, });
    }
    if let Some(lo) = log {
        sub.push(quote! { (#name::#lo, _) | (_, #name::#lo) => #inv, });
    }
    sub.push(quote! { (#name::#v_linear, #name::#v_linear) => #name::#v_linear, });
    if let Some(af) = affine {
        sub.push(quote! { (#name::#af, #name::#v_linear) => #name::#af, });
        sub.push(quote! { (#name::#af, #name::#af) => #name::#v_linear, });
    }
    if let Some(an) = angle {
        sub.push(quote! { (#name::#an, #name::#an) => #name::#an, });
    }
    if let Some(so) = solid {
        sub.push(quote! { (#name::#so, #name::#so) => #name::#so, });
    }
    sub.push(quote! { _ => #inv, });

    Ok(quote! {
        impl ::core::marker::ConstParamTy_ for #name {}
        impl ::core::marker::StructuralPartialEq for #name {}

        impl const ::core::cmp::PartialEq for #name {
            fn eq(&self, rhs: &Self) -> bool {
                matches!(
                    (*self, *rhs),
                    #( (#name::#variant_idents, #name::#variant_idents) )|*
                )
            }
        }
        impl ::core::cmp::Eq for #name {}

        impl const ::core::ops::Mul for #name {
            type Output = Self;
            fn mul(self, rhs: Self) -> Self { match (self, rhs) { #(#mul)* } }
        }
        impl const ::core::ops::Div for #name {
            type Output = Self;
            fn div(self, rhs: Self) -> Self { match (self, rhs) { #(#div)* } }
        }
        impl const ::core::ops::Add for #name {
            type Output = Self;
            fn add(self, rhs: Self) -> Self { match (self, rhs) { #(#add)* } }
        }
        impl const ::core::ops::Sub for #name {
            type Output = Self;
            fn sub(self, rhs: Self) -> Self { match (self, rhs) { #(#sub)* } }
        }

        impl ::yadc::traits::Kind for #name {
            const ZERO: Self = #name::#v_linear;
            const INVALID: Self = #name::#v_invalid;
        }
    })
}

// Generates `impl UcumKind` (variant `name` + the Angle/SolidAngle <-> UCUM
// prefix round-trip) for a Kind enum. Separate from `expand_kind` so the mapping
// is only emitted - and serde only required - when `#[derive(UcumKind)]` is used.
fn expand_ucum_kind(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let (variant_idents, role_map) = kind_roles(input)?;
    let angle = role_map.get("Angle").copied();
    let solid = role_map.get("SolidAngle").copied();

    // Angle <-> "rad", SolidAngle <-> "sr": two halves of one mapping, emitted
    // together so the serialize and deserialize directions can never drift.
    let mut prefix_fwd = Vec::new();
    let mut prefix_rev = Vec::new();
    if let Some(an) = angle {
        prefix_fwd.push(quote! { #name::#an => ::core::option::Option::Some("rad"), });
        prefix_rev.push(quote! { "rad" => ::core::option::Option::Some(#name::#an), });
    }
    if let Some(so) = solid {
        prefix_fwd.push(quote! { #name::#so => ::core::option::Option::Some("sr"), });
        prefix_rev.push(quote! { "sr" => ::core::option::Option::Some(#name::#so), });
    }

    Ok(quote! {
        impl ::yadc::traits::UcumKind for #name {
            fn name(self) -> &'static str {
                match self {
                    #( #name::#variant_idents => ::core::stringify!(#variant_idents), )*
                }
            }

            fn ucum_prefix(self) -> ::core::option::Option<&'static str> {
                match self {
                    #(#prefix_fwd)*
                    _ => ::core::option::Option::None,
                }
            }

            fn from_ucum_prefix(prefix: &str) -> ::core::option::Option<Self> {
                match prefix {
                    #(#prefix_rev)*
                    _ => ::core::option::Option::None,
                }
            }
        }
    })
}

fn expand_dimension(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;

    let fields = match &input.data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => &f.named,
            _ => {
                return Err(syn::Error::new_spanned(
                    name,
                    "#[derive(Dimension)] requires a struct with named fields",
                ));
            }
        },
        _ => {
            return Err(syn::Error::new_spanned(
                name,
                "#[derive(Dimension)] only works on structs",
            ));
        }
    };

    // Partition fields into "numeric" (i8/i16/.. exponents) and "kind" (marked
    // with #[kind] - at most one). Kind field uses .mul/.div/.add/.sub/.eq
    // methods and a ::ZERO + ::INVALID constant on its type.
    let mut numeric_fields: Vec<&syn::Field> = Vec::new();
    let mut kind_field: Option<&syn::Field> = None;
    for f in fields.iter() {
        if f.attrs.iter().any(|a| a.path().is_ident("kind")) {
            if kind_field.is_some() {
                return Err(syn::Error::new_spanned(f, "only one #[kind] field allowed"));
            }
            kind_field = Some(f);
        } else {
            numeric_fields.push(f);
        }
    }

    let num_idents: Vec<&syn::Ident> = numeric_fields
        .iter()
        .filter_map(|f| f.ident.as_ref())
        .collect();

    // Mul: exponents add, kinds multiply.  Div: exponents subtract, kinds divide.
    // Add/Sub: exponents copied from the left operand, kinds add/subtract - but
    // yield the Invalid kind when the operands' numeric axes differ, so a mismatch
    // (e.g. Mass + Force) is caught by `valid()` just like an illegal kind combo.
    let mul_inits: Vec<_> = num_idents
        .iter()
        .map(|f| quote! { #f: a.#f + b.#f })
        .collect();
    let div_inits: Vec<_> = num_idents
        .iter()
        .map(|f| quote! { #f: a.#f - b.#f })
        .collect();
    let copy_inits: Vec<_> = num_idents.iter().map(|f| quote! { #f: a.#f }).collect();
    let zero_inits: Vec<_> = num_idents.iter().map(|f| quote! { #f: 0 }).collect();

    // A `#[kind]` field is required: it carries the Invalid sentinel that makes
    // every operation's validity expressible as `(a op b).valid()`.
    let kf = kind_field.ok_or_else(|| {
        syn::Error::new_spanned(
            name,
            "#[derive(Dimension)] requires exactly one `#[kind]` field",
        )
    })?;
    let k = kf.ident.as_ref().unwrap();
    let kty = &kf.ty;
    let invalid = quote! { <#kty as ::yadc::traits::Kind>::INVALID };
    let kind_mul = quote! { , #k: a.#k * b.#k };
    let kind_div = quote! { , #k: a.#k / b.#k };
    let kind_add_ = quote! { , #k: if a.numeric_eq(b) { a.#k + b.#k } else { #invalid } };
    let kind_sub_ = quote! { , #k: if a.numeric_eq(b) { a.#k - b.#k } else { #invalid } };
    let kind_zero = quote! { , #k: <#kty as ::yadc::traits::Kind>::ZERO };
    let kind_eq_clause = quote! { && self.#k == other.#k };
    let kind_valid_body = quote! { self.#k != #invalid };

    Ok(quote! {
        impl ::core::marker::ConstParamTy_ for #name {}
        impl ::core::marker::StructuralPartialEq for #name {}

        impl const ::core::cmp::PartialEq for #name {
            fn eq(&self, other: &Self) -> bool {
                true #(&& self.#num_idents == other.#num_idents)* #kind_eq_clause
            }
        }
        impl ::core::cmp::Eq for #name {}

        impl const ::core::ops::Mul for #name {
            type Output = Self;
            fn mul(self, rhs: Self) -> Self {
                let (a, b) = (self, rhs);
                #name { #(#mul_inits),* #kind_mul }
            }
        }
        impl const ::core::ops::Div for #name {
            type Output = Self;
            fn div(self, rhs: Self) -> Self {
                let (a, b) = (self, rhs);
                #name { #(#div_inits),* #kind_div }
            }
        }
        impl const ::core::ops::Add for #name {
            type Output = Self;
            #[allow(unused_variables)]
            fn add(self, b: Self) -> Self {
                let a = self;
                #name { #(#copy_inits),* #kind_add_ }
            }
        }
        impl const ::core::ops::Sub for #name {
            type Output = Self;
            #[allow(unused_variables)]
            fn sub(self, b: Self) -> Self {
                let a = self;
                #name { #(#copy_inits),* #kind_sub_ }
            }
        }

        impl #name {
            pub const fn valid(self) -> bool {
                #kind_valid_body
            }
            pub const fn numeric_eq(self, other: Self) -> bool {
                true #(&& self.#num_idents == other.#num_idents)*
            }
            // Value-based equality for use in const generic expressions where
            // the `==` operator's `&self` borrows are not permitted.
            pub const fn dims_eq(self, other: Self) -> bool {
                true #(&& self.#num_idents == other.#num_idents)* #kind_eq_clause
            }
            // `Add`/`Sub` already fold the numeric-axis check into the kind
            // (Invalid on mismatch), so every predicate is just `valid()`; the
            // `*_assign` variants additionally require the result type to be
            // unchanged (`dims_eq`), since an in-place op can't change dimensions.
            pub const fn can_mul(self, b: Self) -> bool {
                (self * b).valid()
            }
            pub const fn can_div(self, b: Self) -> bool {
                (self / b).valid()
            }
            pub const fn can_add(self, b: Self) -> bool {
                (self + b).valid()
            }
            pub const fn can_sub(self, b: Self) -> bool {
                (self - b).valid()
            }
            pub const fn can_add_assign(self, b: Self) -> bool {
                (self + b).dims_eq(self)
            }
            pub const fn can_sub_assign(self, b: Self) -> bool {
                (self - b).dims_eq(self)
            }
        }

        impl ::yadc::Dimension for #name {
            const ZERO: Self = #name { #(#zero_inits),* #kind_zero };
        }
    })
}

/// Derive [`Unit`](::yadc::Unit) for a unit enum.
///
/// `Copy` and `Clone` are NOT generated - add them to `#[derive(...)]`
/// yourself (the `Unit` trait requires `Copy`).
///
/// Each variant carries exactly one conversion attribute naming its family.
/// The first two arguments are always `"short"` then `"long"`; the rest are
/// the family's numeric parameters. Every argument may instead be passed by
/// keyword (`short`, `long`, `scale`, `offset`, `base`, `coeff`, `reference`)
/// in any order, and each value is an arbitrary expression.
///
/// | Attribute | canonical (SI) value | numerics |
/// |---|---|---|
/// | `#[linear("s", "l", scale)]` | `value * scale` | `scale` |
/// | `#[affine("s", "l", scale, offset)]` | `(value + offset) * scale` | `scale`, `offset` |
/// | `#[log("s", "l", base, coeff)]` | `reference * base.powf(coeff * value)` | `base`, `coeff`, `reference` (default `1`) |
/// | `#[tan("s", "l", coeff)]` | `reference * (value / coeff).atan()` | `coeff`, `reference` (default `1`) |
///
/// `log` covers every logarithmic unit by choice of `base`: `10.0` for
/// decibel/bel, `core::f64::consts::E` for neper, `2.0` for bit; a negative
/// `coeff` gives the negated-log scales (e.g. pH). `log` and `tan` require
/// `V: num_traits::real::Real`.
///
/// Enum-level attributes:
/// - `#[dim(QtyAlias)]` (required) - names the quantity this unit measures
///   (becomes [`Unit::Quantity`](::yadc::Unit::Quantity)).
///
/// ```ignore
/// #[derive(Unit, Copy, Clone)]
/// #[dim(Mass)]
/// pub enum MassUnit {
///     #[linear("kg", "kilograms", 1.0)]   Kilogram,
///     #[linear("g", "grams", 0.001)]      Gram,
/// }
///
/// #[derive(Unit, Copy, Clone)]
/// #[dim(Temperature)]
/// pub enum TempUnit {
///     #[linear("K", "kelvin", 1.0)]            Kelvin,
///     #[affine("°C", "celsius", 1.0, 273.15)]  Celsius,
/// }
/// ```
#[proc_macro_derive(Unit, attributes(dim, linear, affine, log, tan))]
pub fn derive_unit(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_unit(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

fn expand_unit(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;

    // `#[dim(QtyType)]` - the quantity this unit measures (e.g. `Mass`,
    // `Temperature`). Becomes `Unit::Quantity`. Required.
    let qty_ty = find_attr_type(input, "dim")?.ok_or_else(|| {
        syn::Error::new_spanned(name, "missing #[dim(StaticQuantityAlias)] on unit enum")
    })?;
    let variants = match &input.data {
        Data::Enum(e) => &e.variants,
        _ => {
            return Err(syn::Error::new_spanned(
                name,
                "#[derive(Unit)] only works on enums",
            ));
        }
    };

    // Per variant: the SI<->unit scalar conversion, plus labels.
    //   linear (multiplier M):  canonical = value * M ;        value = canonical / M
    //   affine (M, offset F):   canonical = (value + F) * M ;  value = canonical / M - F
    // where `offset_in_SI = M * F`, matching the legacy `o` semantics.
    let mut to_canon_arms = Vec::new();
    let mut from_canon_arms = Vec::new();
    let mut symbol_arms = Vec::new();
    let mut long_arms = Vec::new();

    // `V` for nonlinear (Real) bodies and the `reference` default.
    let vty = quote! { <#qty_ty as ::yadc::Quantity>::V };

    for variant in variants {
        let ident = &variant.ident;
        let spec = parse_unit_spec(variant)?;
        let symbol = &spec.symbol;
        let long = &spec.long;
        symbol_arms.push(quote! { Self::#ident => #symbol, });
        long_arms.push(quote! { Self::#ident => #long, });

        // `reference` (log/tan) defaults to the multiplicative identity.
        let one = quote! { <#vty as ::yadc::num_traits::One>::one() };
        let reference = |r: &Option<Expr>| {
            r.as_ref()
                .map(|e| quote! { (#e) })
                .unwrap_or_else(|| quote! { (#one) })
        };

        // Scalar value <-> canonical(SI) conversion for this unit.
        //   linear:  canonical = value * scale
        //   affine:  canonical = (value + offset) * scale
        //   log:     canonical = reference * base^(coeff * value)
        //   tan:     canonical = reference * atan(value / coeff)
        let (to_expr, from_expr) = match &spec.kind {
            UnitKind::Linear { scale } => (
                quote! { value * (#scale) },
                quote! { __canonical / (#scale) },
            ),
            UnitKind::Affine { scale, offset } => (
                quote! { (value + (#offset)) * (#scale) },
                quote! { __canonical / (#scale) - (#offset) },
            ),
            UnitKind::Log {
                base,
                coeff,
                reference: r,
            } => {
                let r = reference(r);
                (
                    quote! { #r * ::yadc::num_traits::real::Real::powf((#base), value * (#coeff)) },
                    quote! { ::yadc::num_traits::real::Real::log(__canonical / #r, (#base)) / (#coeff) },
                )
            }
            UnitKind::Tan { coeff, reference: r } => {
                let r = reference(r);
                (
                    quote! { #r * ::yadc::num_traits::real::Real::atan(value / (#coeff)) },
                    quote! { (#coeff) * ::yadc::num_traits::real::Real::tan(__canonical / #r) },
                )
            }
        };
        to_canon_arms.push(quote! { Self::#ident => #to_expr, });
        from_canon_arms.push(quote! { Self::#ident => #from_expr, });
    }

    Ok(quote! {
        impl ::yadc::Unit for #name {
            type Quantity = #qty_ty;

            fn quantity(
                self,
                value: <#qty_ty as ::yadc::Quantity>::V,
            ) -> #qty_ty {
                let __canonical = match self { #(#to_canon_arms)* };
                <#qty_ty>::from_canonical(__canonical)
            }

            fn from_quantity(
                self,
                q: #qty_ty,
            ) -> <#qty_ty as ::yadc::Quantity>::V {
                let __canonical: <#qty_ty as ::yadc::Quantity>::V = (q
                    / <#qty_ty>::from_canonical(
                        <<#qty_ty as ::yadc::Quantity>::V as ::yadc::num_traits::One>::one(),
                    ))
                .into();
                match self { #(#from_canon_arms)* }
            }

            fn symbol(self) -> &'static str { match self { #(#symbol_arms)* } }
            fn long(self)   -> &'static str { match self { #(#long_arms)* } }
        }
    })
}

/// Derive [`Quantity`](::yadc::Quantity), arithmetic operators, and supporting
/// inherent items for a tuple struct with one const-generic `Dimension`
/// parameter (the statically-dimensioned `Qty<const D: Dim>`).
///
/// Emitted impls:
/// - `Copy`, `Clone`, `PartialEq`.
/// - `Quantity` trait - the marker exposing `D` and `V`. Conversion is unit-led
///   (`unit.quantity` / `unit.from_quantity` / `unit.format_quantity`).
/// - inherent `const DIM`.
/// - inherent `from_canonical(value) -> Self` - constructs from a base-unit
///   value; the `Unit` derive lifts with it and reads back by dividing by
///   `from_canonical(one)`. This is the construction path that bypasses the
///   kind-gated scalar `Mul`, so affine quantities still build. Reading back
///   needs `num_traits::One`; `Sum` uses `num_traits::Zero` (every numeric type
///   has both).
/// - **scalar `Mul<V>`/`Div<V>` are kind-gated** (`Assert<{ D.can_add(D) }>`):
///   only self-addable kinds scale, so an affine quantity can't be multiplied by
///   a scalar (just as `Affine + Affine` is rejected).
/// - `Into<V>` for `Qty<{ D::ZERO }>` - the single sanctioned value-extraction
///   path, used by `Unit::from_quantity` after dividing out the unit.
/// - `Display` and `Debug` that print `value` followed by the `Debug` of the
///   dim when non-zero.
/// - `Mul`/`Div`/`Add`/`Sub` (cross-dim where applicable) - with dimension
///   composition through the user's [`Dim`](macro@Dimension) tables, guarded
///   by compile-time `Assert<{ ... }>: IsTrue` predicates.
/// - `Default` and `Neg` when `Qty<D> += Qty<D>` is valid.
/// - `Sum<Qty<D>>` / `Sum<&Qty<D>>` when `Qty<D> += Qty<D>` is valid.
/// - Borrowed `AddAssign` / `SubAssign`, `PartialOrd`, and dimensionless
///   `MulAssign` / `DivAssign`.
///
/// ```ignore
/// #[derive(StaticQuantity)]
/// pub struct Qty<const D: Dim>(f64);
/// ```
#[proc_macro_derive(StaticQuantity, attributes(dim))]
pub fn derive_static_quantity(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_quantity(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

fn expand_quantity(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;

    let value_ty = single_tuple_field(&input.data, name)?;
    let (d_ident, d_ty) = single_const_param(&input.generics, name)?;

    let qa = syn::Ident::new("__QA", Span::call_site());
    let qb = syn::Ident::new("__QB", Span::call_site());

    Ok(quote! {
        impl<const #d_ident: #d_ty> ::yadc::Quantity for #name<#d_ident> {
            type D = #d_ty;
            type V = #value_ty;
        }

        impl<const #d_ident: #d_ty> #name<#d_ident> {
            pub const DIM: #d_ty = #d_ident;

            /// Construct from a value already in the system's base units.
            /// The `Unit` derive lifts a converted scalar with `from_canonical`
            /// and reads it back as `(q / from_canonical(one)).into()` (dividing by
            /// one base unit). This is the construction path that bypasses the
            /// kind-gated scalar `Mul`, so affine quantities can still be built;
            /// `Sum` separately seeds with `num_traits::Zero`.
            pub fn from_canonical(value: #value_ty) -> Self { Self(value) }
        }

        impl ::core::convert::Into<#value_ty>
            for #name<{ <#d_ty as ::yadc::Dimension>::ZERO }>
        {
            fn into(self) -> #value_ty { self.0 }
        }

        impl<const #d_ident: #d_ty>
            ::core::convert::Into<::core::option::Option<#value_ty>>
            for #name<#d_ident>
        {
            fn into(self) -> ::core::option::Option<#value_ty> {
                if #d_ident == <#d_ty as ::yadc::Dimension>::ZERO {
                    ::core::option::Option::Some(self.0)
                } else {
                    ::core::option::Option::None
                }
            }
        }

        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::Mul<#name<#qb>> for #name<#qa>
        where
            #name<{ #qa * #qb }>: Sized,
            ::yadc::Assert<{ #qa.can_mul(#qb) }>: ::yadc::IsTrue,
        {
            type Output = #name<{ #qa * #qb }>;
            fn mul(self, rhs: #name<#qb>) -> Self::Output { #name(self.0 * rhs.0) }
        }

        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::Div<#name<#qb>> for #name<#qa>
        where
            #name<{ #qa / #qb }>: Sized,
            ::yadc::Assert<{ #qa.can_div(#qb) }>: ::yadc::IsTrue,
        {
            type Output = #name<{ #qa / #qb }>;
            fn div(self, rhs: #name<#qb>) -> Self::Output { #name(self.0 / rhs.0) }
        }

        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::Add<#name<#qb>> for #name<#qa>
        where
            #name<{ #qa + #qb }>: Sized,
            ::yadc::Assert<{ #qa.can_add(#qb) }>: ::yadc::IsTrue,
        {
            type Output = #name<{ #qa + #qb }>;
            fn add(self, rhs: #name<#qb>) -> Self::Output { #name(self.0 + rhs.0) }
        }

        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::Sub<#name<#qb>> for #name<#qa>
        where
            #name<{ #qa - #qb }>: Sized,
            ::yadc::Assert<{ #qa.can_sub(#qb) }>: ::yadc::IsTrue,
        {
            type Output = #name<{ #qa - #qb }>;
            fn sub(self, rhs: #name<#qb>) -> Self::Output { #name(self.0 - rhs.0) }
        }

        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::AddAssign<#name<#qb>> for #name<#qa>
        where
            ::yadc::Assert<{ #qa.can_add_assign(#qb) }>: ::yadc::IsTrue,
        {
            fn add_assign(&mut self, rhs: #name<#qb>) { self.0 += rhs.0; }
        }
        impl<'__a, const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::AddAssign<&'__a #name<#qb>> for #name<#qa>
        where
            ::yadc::Assert<{ #qa.can_add_assign(#qb) }>: ::yadc::IsTrue,
        {
            fn add_assign(&mut self, rhs: &'__a #name<#qb>) { self.0 += rhs.0; }
        }
        impl<const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::SubAssign<#name<#qb>> for #name<#qa>
        where
            ::yadc::Assert<{ #qa.can_sub_assign(#qb) }>: ::yadc::IsTrue,
        {
            fn sub_assign(&mut self, rhs: #name<#qb>) { self.0 -= rhs.0; }
        }
        impl<'__a, const #qa: #d_ty, const #qb: #d_ty>
            ::core::ops::SubAssign<&'__a #name<#qb>> for #name<#qa>
        where
            ::yadc::Assert<{ #qa.can_sub_assign(#qb) }>: ::yadc::IsTrue,
        {
            fn sub_assign(&mut self, rhs: &'__a #name<#qb>) { self.0 -= rhs.0; }
        }

        impl<const #d_ident: #d_ty> ::core::ops::Neg for #name<#d_ident>
        where
            #value_ty: ::core::ops::Neg<Output = #value_ty>,
            ::yadc::Assert<{ #d_ident.can_add_assign(#d_ident) }>: ::yadc::IsTrue,
        {
            type Output = Self;
            fn neg(self) -> Self { #name(-self.0) }
        }

        impl<const #d_ident: #d_ty> ::core::iter::Sum<#name<#d_ident>> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add_assign(#d_ident) }>: ::yadc::IsTrue,
        {
            fn sum<__I>(iter: __I) -> Self
            where
                __I: ::core::iter::Iterator<Item = #name<#d_ident>>,
            {
                iter.fold(#name(<#value_ty as ::yadc::num_traits::Zero>::zero()), |mut __acc, __q| {
                    __acc += __q;
                    __acc
                })
            }
        }

        impl<'__a, const #d_ident: #d_ty> ::core::iter::Sum<&'__a #name<#d_ident>> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add_assign(#d_ident) }>: ::yadc::IsTrue,
        {
            fn sum<__I>(iter: __I) -> Self
            where
                __I: ::core::iter::Iterator<Item = &'__a #name<#d_ident>>,
            {
                iter.fold(#name(<#value_ty as ::yadc::num_traits::Zero>::zero()), |mut __acc, __q| {
                    __acc += *__q;
                    __acc
                })
            }
        }

        // Scalar scaling is only meaningful for kinds that may be added to
        // themselves: `n * x` is repeated addition, which an affine (absolute)
        // kind forbids (`Affine + Affine = Invalid`). So gate on `can_add(D, D)`
        // (= `(D + D).valid()`). Construction never relies on these - the `Unit`
        // derive lifts a value with `from_canonical`, not scalar `*`.
        impl<const #d_ident: #d_ty> ::core::ops::Mul<#value_ty> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add(#d_ident) }>: ::yadc::IsTrue,
        {
            type Output = Self;
            fn mul(self, rhs: #value_ty) -> Self { #name(self.0 * rhs) }
        }
        impl<const #d_ident: #d_ty> ::core::ops::Mul<#name<#d_ident>> for #value_ty
        where
            ::yadc::Assert<{ #d_ident.can_add(#d_ident) }>: ::yadc::IsTrue,
        {
            type Output = #name<#d_ident>;
            fn mul(self, rhs: #name<#d_ident>) -> #name<#d_ident> { #name(self * rhs.0) }
        }
        impl<const #d_ident: #d_ty> ::core::ops::Div<#value_ty> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add(#d_ident) }>: ::yadc::IsTrue,
        {
            type Output = Self;
            fn div(self, rhs: #value_ty) -> Self { #name(self.0 / rhs) }
        }
        impl<const #d_ident: #d_ty> ::core::ops::MulAssign<#value_ty> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add(#d_ident) }>: ::yadc::IsTrue,
        {
            fn mul_assign(&mut self, rhs: #value_ty) { self.0 *= rhs; }
        }
        impl<const #d_ident: #d_ty> ::core::ops::DivAssign<#value_ty> for #name<#d_ident>
        where
            ::yadc::Assert<{ #d_ident.can_add(#d_ident) }>: ::yadc::IsTrue,
        {
            fn div_assign(&mut self, rhs: #value_ty) { self.0 /= rhs; }
        }
        impl<const #d_ident: #d_ty>
            ::core::ops::MulAssign<#name<{ <#d_ty as ::yadc::Dimension>::ZERO }>>
            for #name<#d_ident>
        where
            ::yadc::Assert<{
                (#d_ident * <#d_ty as ::yadc::Dimension>::ZERO).dims_eq(#d_ident)
            }>: ::yadc::IsTrue,
        {
            fn mul_assign(&mut self, rhs: #name<{ <#d_ty as ::yadc::Dimension>::ZERO }>) {
                self.0 *= rhs.0;
            }
        }
        impl<const #d_ident: #d_ty>
            ::core::ops::DivAssign<#name<{ <#d_ty as ::yadc::Dimension>::ZERO }>>
            for #name<#d_ident>
        where
            ::yadc::Assert<{
                (#d_ident / <#d_ty as ::yadc::Dimension>::ZERO).dims_eq(#d_ident)
            }>: ::yadc::IsTrue,
        {
            fn div_assign(&mut self, rhs: #name<{ <#d_ty as ::yadc::Dimension>::ZERO }>) {
                self.0 /= rhs.0;
            }
        }
    })
}

// UcumSerialize / UcumDeserialize - emit a UCUM-compliant string for
// a Dimension struct. Angle kind -> "rad[.axes]", SolidAngle -> "sr[.axes]",
// all-zero Linear -> "1". Other kinds serialize without a kind annotation;
// the kind is recovered from schema context on deserialize.
/// Derive a UCUM-compliant `serde::Serialize` impl for a Dimension struct.
///
/// Axes are dot-joined with exponents written directly after the symbol
/// (e.g. `s-2`, not `s^-2`). The `#[kind]` field produces a UCUM unit prefix
/// for `Angle` (`"rad"`) and `SolidAngle` (`"sr"`); other kinds produce no
/// annotation. A fully zero dimension serializes as `"1"`.
///
/// ```text
/// "m.kg.s-2"   // Force
/// "K"          // ThermodynamicTemperature (Affine kind not encoded - infer from schema)
/// "K"          // TemperatureInterval (Linear K)
/// "rad"        // Angle
/// "rad.s-1"    // AngularVelocity
/// "sr"         // SolidAngle
/// "1"          // Dimensionless
/// ```
///
/// Pair with [`UcumDeserialize`](macro@UcumDeserialize) to
/// round-trip. Both impls are emitted unconditionally - gate them behind a
/// feature in your crate with
/// `#[cfg_attr(feature = "serde", derive(...))]` if serde should be optional.
#[proc_macro_derive(UcumSerialize)]
pub fn derive_ucum_serialize(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_ucum_serialize(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

// (numeric_fields, kind_field). The kind field is identified by `#[kind]`.
type DimFields = (Vec<(syn::Ident, String)>, Option<(syn::Ident, Type)>);

// Returns (numeric_fields, kind_field) - same shape as expand_dimension.
fn dim_fields(input: &DeriveInput) -> syn::Result<DimFields> {
    let fields = match &input.data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => &f.named,
            _ => {
                return Err(syn::Error::new_spanned(
                    &input.ident,
                    "UcumSerialize/Deserialize requires a struct with named fields",
                ));
            }
        },
        _ => {
            return Err(syn::Error::new_spanned(
                &input.ident,
                "UcumSerialize/Deserialize only works on structs",
            ));
        }
    };
    let mut numeric = Vec::new();
    let mut kind: Option<(syn::Ident, Type)> = None;
    for f in fields {
        let is_kind = f.attrs.iter().any(|a| a.path().is_ident("kind"));
        let Some(id) = f.ident.clone() else {
            continue;
        };
        if is_kind {
            kind = Some((id, f.ty.clone()));
        } else {
            let s = id.to_string();
            numeric.push((id, s));
        }
    }
    Ok((numeric, kind))
}

fn expand_ucum_serialize(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let (axes, kind) = dim_fields(input)?;

    // UCUM kind prefix: "rad" for Angle, "sr" for SolidAngle, nothing otherwise.
    let kind_prefix = match &kind {
        Some((k, kty)) => quote! {
            if let ::core::option::Option::Some(__prefix) =
                <#kty as ::yadc::traits::UcumKind>::ucum_prefix(self.#k)
            {
                __buf.push_str(__prefix);
                __first = false;
            }
        },
        None => quote! {},
    };

    // Axis entries: dot-separated, exponent directly after symbol (UCUM style).
    let axis_entries = axes.iter().map(|(ident, sym)| {
        quote! {
            {
                let __v = self.#ident;
                if __v != 0 {
                    if !__first { __buf.push('.'); }
                    if __v == 1 {
                        __buf.push_str(#sym);
                    } else {
                        let _ = ::core::fmt::Write::write_fmt(
                            &mut __buf,
                            ::core::format_args!("{}{}", #sym, __v),
                        );
                    }
                    __first = false;
                }
            }
        }
    });

    // UCUM annotation suffix {KindName} for non-prefix, non-zero kinds (the kinds
    // a prefix or the bare axes can't already distinguish, e.g. Affine vs Linear).
    let kind_annotation = match &kind {
        Some((k, kty)) => quote! {
            if <#kty as ::yadc::traits::UcumKind>::ucum_prefix(self.#k).is_none()
                && self.#k != <#kty as ::yadc::traits::Kind>::ZERO
            {
                __buf.push('{');
                __buf.push_str(<#kty as ::yadc::traits::UcumKind>::name(self.#k));
                __buf.push('}');
            }
        },
        None => quote! {},
    };

    Ok(quote! {
        const _: () = {
            extern crate alloc as __yadc_alloc;
            impl ::serde::Serialize for #name {
                fn serialize<__S: ::serde::Serializer>(
                    &self,
                    __ser: __S,
                ) -> ::core::result::Result<__S::Ok, __S::Error> {
                    let mut __buf = __yadc_alloc::string::String::new();
                    let mut __first = true;
                    #kind_prefix
                    #(#axis_entries)*
                    // UCUM "1" for a dimensionless/kind-less quantity.
                    if __first { __buf.push('1'); }
                    let _ = __first;
                    #kind_annotation
                    __ser.serialize_str(&__buf)
                }
            }
        };
    })
}

/// Derive a `serde::Deserialize` impl matching
/// [`UcumSerialize`](macro@UcumSerialize).
///
/// Parses a UCUM unit string: `"1"` produces the zero dimension; `"rad[.axes]"`
/// sets `Kind::Angle`; `"sr[.axes]"` sets `Kind::SolidAngle`; otherwise axes
/// are parsed from dot-separated tokens with direct exponents (`m2`, `s-2`).
/// Missing axes default to 0; kind defaults to `<Kind>::ZERO` unless a UCUM
/// prefix is present. Unknown unit symbols produce a `serde::de::Error::custom`.
#[proc_macro_derive(UcumDeserialize)]
pub fn derive_ucum_deserialize(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_ucum_deserialize(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

fn expand_ucum_deserialize(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let (axes, kind) = dim_fields(input)?;

    // Sort by symbol length descending so longer symbols are tried first
    // (avoids "m" matching the start of "mol" or "mg").
    let mut sorted_axes = axes.clone();
    sorted_axes.sort_by(|(_, a), (_, b)| b.len().cmp(&a.len()));

    // Generate an if-else chain: for each token, strip the known symbol prefix
    // and parse the remainder as an i8 exponent (empty -> 1).
    let parse_chain = sorted_axes.iter().map(|(ident, sym)| {
        let len = sym.len();
        quote! {
            else if __tok.starts_with(#sym) {
                let __exp_str = &__tok[#len..];
                let __exp: i8 = if __exp_str.is_empty() {
                    1i8
                } else {
                    __exp_str.parse::<i8>().map_err(|_| {
                        <__D::Error as ::serde::de::Error>::custom(
                            __yadc_alloc::format!("bad exponent in `{}`", __tok),
                        )
                    })?
                };
                __out.#ident = __exp;
            }
        }
    });

    // Strip a trailing {KindName} annotation and parse it via serde to recover
    // non-prefix kinds (e.g. "K{Affine}"). The remaining string is then processed
    // for UCUM prefix / axes as normal.
    let annotation_extract = match &kind {
        Some((k, kty)) => quote! {
            let __s: &str = if __s.ends_with('}') {
                if let ::core::option::Option::Some(__open) = __s.rfind('{') {
                    let __ann = &__s[__open + 1..__s.len() - 1];
                    let __kind_de =
                        ::serde::de::value::StrDeserializer::<__D::Error>::new(__ann);
                    __out.#k = <#kty as ::serde::Deserialize>::deserialize(__kind_de)
                        .map_err(|_| {
                            <__D::Error as ::serde::de::Error>::custom(
                                __yadc_alloc::format!("unknown kind `{}`", __ann),
                            )
                        })?;
                    __s[..__open].trim_end()
                } else {
                    &__s
                }
            } else {
                &__s
            };
        },
        None => quote! { let __s: &str = &__s; },
    };

    // Kind prefix detection. "1" is the dimensionless unit. Otherwise the first
    // dot-separated token is offered to `Kind::from_ucum_prefix`; if it names a
    // prefix-bearing kind (e.g. "rad" -> Angle, "sr" -> SolidAngle) we set the
    // kind and continue with the remaining axes. This is the exact inverse of
    // the `ucum_prefix` used during serialization, so the mapping lives in one
    // place (the Kind derive) rather than being duplicated here.
    let kind_prefix_extract = match &kind {
        Some((k, kty)) => quote! {
            let __axes: &str = if __s == "1" {
                return ::core::result::Result::Ok(__out);
            } else {
                let (__head, __rest) = match __s.find('.') {
                    ::core::option::Option::Some(__i) => (&__s[..__i], &__s[__i + 1..]),
                    ::core::option::Option::None => (__s, ""),
                };
                if let ::core::option::Option::Some(__k) =
                    <#kty as ::yadc::traits::UcumKind>::from_ucum_prefix(__head)
                {
                    __out.#k = __k;
                    if __rest.is_empty() {
                        return ::core::result::Result::Ok(__out);
                    }
                    __rest
                } else {
                    __s
                }
            };
        },
        None => quote! {
            let __axes: &str =
                if __s == "1" { return ::core::result::Result::Ok(__out); }
                else { __s };
        },
    };

    Ok(quote! {
        const _: () = {
            extern crate alloc as __yadc_alloc;
            impl<'de> ::serde::Deserialize<'de> for #name {
                fn deserialize<__D: ::serde::Deserializer<'de>>(
                    __de: __D,
                ) -> ::core::result::Result<Self, __D::Error> {
                    let __s: __yadc_alloc::string::String =
                        <__yadc_alloc::string::String as ::serde::Deserialize>::deserialize(__de)?;
                    let mut __out = <#name as ::yadc::Dimension>::ZERO;
                    #annotation_extract
                    #kind_prefix_extract
                    for __tok in __axes.split('.') {
                        if false { unreachable!() }
                        #(#parse_chain)*
                        else {
                            return ::core::result::Result::Err(
                                <__D::Error as ::serde::de::Error>::custom(
                                    __yadc_alloc::format!("unknown unit `{}`", __tok),
                                ),
                            );
                        }
                    }
                    ::core::result::Result::Ok(__out)
                }
            }
        };
    })
}

/// Derive [`Quantity`](::yadc::Quantity) and runtime-dim arithmetic for a
/// named-field struct carrying a value and a dimension (the dynamically-
/// dimensioned `DynQty`).
///
/// Requires `#[static_quantity(Qty)]` naming the companion static quantity type.
/// The value field is identified by a `#[value]` attribute or by the name
/// `value`; the dim field is identified by a `#[dim]` attribute or by the
/// name `dim`. Emits:
/// - `Quantity` trait impl (`type D`, `type V`).
/// - `Into<Option<V>>` - `Some(v)` when dimensionless, `None` otherwise.
/// - `Mul`/`Div` (return `Option`; dims combine via the user's
///   [`Dim`](macro@Dimension) tables, `None` on an `Invalid`-kind result).
/// - `Add`/`Sub` (return `Option`; `None` on dim mismatch).
/// - Scalar `Mul<V>` / `Div<V>` returning `Option` (`None` for a non-self-addable
///   kind, e.g. affine - scaling an absolute is meaningless).
/// - `From<Qty<D>> for DynQty` and `TryFrom<DynQty> for Qty<D>`.
///
/// ```ignore
/// #[derive(Copy, Clone, PartialEq, DynamicQuantity)]
/// #[static_quantity(Qty)]
/// pub struct DynQty {
///     value: f64,
///     dim: Dim,
/// }
///
/// // Custom field names via marker attributes:
/// #[derive(Copy, Clone, PartialEq, DynamicQuantity)]
/// #[static_quantity(Qty)]
/// pub struct DynQty {
///     #[value] v: f64,
///     #[dim]   d: Dim,
/// }
/// ```
#[proc_macro_derive(DynamicQuantity, attributes(static_quantity, value, dim))]
pub fn derive_dynamic_quantity(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand_dyn_quantity(&input)
        .unwrap_or_else(|e| e.to_compile_error())
        .into()
}

fn expand_dyn_quantity(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;

    let qty_ty = find_attr_type(input, "static_quantity")?.ok_or_else(|| {
        syn::Error::new_spanned(
            name,
            "missing #[static_quantity(QtyType)] on DynamicQuantity struct",
        )
    })?;

    let (val_ident, value_ty, dim_ident, dims_ty) = named_value_dims_fields(&input.data, name)?;

    let d = syn::Ident::new("__D", Span::call_site());
    let d_ty = &dims_ty;

    Ok(quote! {
        impl ::core::convert::Into<::core::option::Option<#value_ty>> for #name {
            // Returns Some only for dimensionless quantities (dim == D::ZERO).
            fn into(self) -> ::core::option::Option<#value_ty> {
                if self.#dim_ident == <#d_ty as ::yadc::Dimension>::ZERO {
                    ::core::option::Option::Some(self.#val_ident)
                } else {
                    ::core::option::Option::None
                }
            }
        }

        impl ::yadc::Quantity for #name {
            type D = #d_ty;
            type V = #value_ty;
        }

        // `Mul`/`Div` combine dimensions but can still yield an `Invalid` kind
        // (e.g. `Angle * SolidAngle`, or any affine operand), so they return
        // `Option` - `None` on an invalid result - mirroring `Add`/`Sub` and the
        // static `Qty`'s compile-time `can_mul`/`can_div` gate. Every `DynQty`
        // arithmetic op is therefore `Option`-returning.
        impl ::core::ops::Mul for #name {
            type Output = ::core::option::Option<#name>;
            fn mul(self, rhs: #name) -> ::core::option::Option<#name> {
                self.#dim_ident.can_mul(rhs.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident * rhs.#val_ident,
                    #dim_ident: self.#dim_ident * rhs.#dim_ident,
                })
            }
        }
        impl ::core::ops::Div for #name {
            type Output = ::core::option::Option<#name>;
            fn div(self, rhs: #name) -> ::core::option::Option<#name> {
                self.#dim_ident.can_div(rhs.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident / rhs.#val_ident,
                    #dim_ident: self.#dim_ident / rhs.#dim_ident,
                })
            }
        }

        impl ::core::ops::Add for #name {
            type Output = ::core::option::Option<#name>;
            fn add(self, rhs: #name) -> ::core::option::Option<#name> {
                self.#dim_ident.can_add(rhs.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident + rhs.#val_ident,
                    #dim_ident: self.#dim_ident + rhs.#dim_ident,
                })
            }
        }
        impl ::core::ops::Sub for #name {
            type Output = ::core::option::Option<#name>;
            fn sub(self, rhs: #name) -> ::core::option::Option<#name> {
                self.#dim_ident.can_sub(rhs.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident - rhs.#val_ident,
                    #dim_ident: self.#dim_ident - rhs.#dim_ident,
                })
            }
        }

        // Scalar scaling returns `Option` (mirroring `Add`/`Sub`): `None` for a
        // kind that can't be added to itself, e.g. an affine (absolute) dim, since
        // `n * x` is repeated addition. The static `Qty` gates the same case at
        // compile time; `DynQty` carries its kind at runtime, so it checks here.
        impl ::core::ops::Mul<#value_ty> for #name {
            type Output = ::core::option::Option<#name>;
            fn mul(self, rhs: #value_ty) -> ::core::option::Option<#name> {
                self.#dim_ident.can_add(self.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident * rhs,
                    #dim_ident: self.#dim_ident,
                })
            }
        }
        impl ::core::ops::Div<#value_ty> for #name {
            type Output = ::core::option::Option<#name>;
            fn div(self, rhs: #value_ty) -> ::core::option::Option<#name> {
                self.#dim_ident.can_add(self.#dim_ident).then(|| #name {
                    #val_ident: self.#val_ident / rhs,
                    #dim_ident: self.#dim_ident,
                })
            }
        }

        impl<const #d: #d_ty> ::core::convert::From<#qty_ty<#d>> for #name {
            fn from(q: #qty_ty<#d>) -> Self {
                Self { #val_ident: q.0, #dim_ident: #d }
            }
        }
        impl<const #d: #d_ty> ::core::convert::TryFrom<#name> for #qty_ty<#d> {
            type Error = ();
            fn try_from(dyn_qty: #name) -> ::core::result::Result<#qty_ty<#d>, ()> {
                if dyn_qty.#dim_ident == #d {
                    ::core::result::Result::Ok(<#qty_ty<#d>>::from_canonical(dyn_qty.#val_ident))
                } else {
                    ::core::result::Result::Err(())
                }
            }
        }

    })
}

fn single_tuple_field(data: &Data, span: &impl quote::ToTokens) -> syn::Result<Type> {
    match data {
        Data::Struct(s) => match &s.fields {
            Fields::Unnamed(f) if f.unnamed.len() == 1 => Ok(f.unnamed.first().unwrap().ty.clone()),
            _ => Err(syn::Error::new_spanned(
                span,
                "expected a single-field tuple struct, e.g. struct Qty<const D: Dims>(f64)",
            )),
        },
        _ => Err(syn::Error::new_spanned(
            span,
            "#[derive(Qty)] only works on structs",
        )),
    }
}

fn single_const_param<'a>(
    generics: &'a syn::Generics,
    span: &impl quote::ToTokens,
) -> syn::Result<(&'a syn::Ident, &'a Type)> {
    let mut first = None;
    for p in &generics.params {
        if let GenericParam::Const(c) = p {
            if c.attrs.iter().any(|a| a.path().is_ident("dim")) {
                return Ok((&c.ident, &c.ty));
            }
            first.get_or_insert(c);
        }
    }
    match first {
        Some(c) => Ok((&c.ident, &c.ty)),
        None => Err(syn::Error::new_spanned(
            span,
            "expected one const generic parameter, e.g. `#[dim] const D: MyDim`",
        )),
    }
}

// Returns (value_ident, value_ty, dim_ident, dim_ty).
// Fields are discovered by a `#[value]` / `#[dim]` marker attribute first,
// then by name (`"value"` / `"dim"`) as a fallback.
fn named_value_dims_fields(
    data: &Data,
    span: &impl quote::ToTokens,
) -> syn::Result<(syn::Ident, Type, syn::Ident, Type)> {
    let fields = match data {
        Data::Struct(s) => match &s.fields {
            Fields::Named(f) => f,
            _ => {
                return Err(syn::Error::new_spanned(
                    span,
                    "#[derive(DynamicQuantity)] requires a named-field struct",
                ));
            }
        },
        _ => {
            return Err(syn::Error::new_spanned(
                span,
                "#[derive(DynamicQuantity)] only works on structs",
            ));
        }
    };

    let mut val_field: Option<(syn::Ident, Type)> = None;
    let mut dim_field: Option<(syn::Ident, Type)> = None;

    for f in &fields.named {
        let Some(ident) = f.ident.clone() else {
            continue;
        };
        let has_value = f.attrs.iter().any(|a| a.path().is_ident("value"));
        let has_dim = f.attrs.iter().any(|a| a.path().is_ident("dim"));
        if has_value {
            val_field = Some((ident.clone(), f.ty.clone()));
        }
        if has_dim {
            dim_field = Some((ident, f.ty.clone()));
        }
    }

    // Name-based fallback (only when no attribute marked the field).
    if val_field.is_none() {
        val_field = fields
            .named
            .iter()
            .find(|f| f.ident.as_ref().map(|i| i == "value").unwrap_or(false))
            .map(|f| (f.ident.clone().unwrap(), f.ty.clone()));
    }
    if dim_field.is_none() {
        dim_field = fields
            .named
            .iter()
            .find(|f| f.ident.as_ref().map(|i| i == "dim").unwrap_or(false))
            .map(|f| (f.ident.clone().unwrap(), f.ty.clone()));
    }

    let (val_ident, val_ty) = val_field.ok_or_else(|| {
        syn::Error::new_spanned(
            span,
            "no `#[value]` field and no field named `value` on DynamicQuantity struct",
        )
    })?;
    let (dim_ident, dim_ty) = dim_field.ok_or_else(|| {
        syn::Error::new_spanned(
            span,
            "no `#[dim]` field and no field named `dim` on DynamicQuantity struct",
        )
    })?;

    Ok((val_ident, val_ty, dim_ident, dim_ty))
}

fn find_attr_type(input: &DeriveInput, attr_name: &str) -> syn::Result<Option<syn::Path>> {
    for attr in &input.attrs {
        if attr.path().is_ident(attr_name) {
            return Ok(Some(attr.parse_args::<syn::Path>()?));
        }
    }
    Ok(None)
}

/// A unit variant's parsed `#[linear|affine|log|tan(...)]` spec.
struct UnitSpec {
    symbol: String,
    long: String,
    kind: UnitKind,
}

/// The conversion family of a unit (one attribute each). `scale`/`offset`/
/// `base`/`coeff`/`reference` are arbitrary value-typed expressions.
enum UnitKind {
    /// `canonical = value * scale`
    Linear { scale: Expr },
    /// `canonical = (value + offset) * scale`
    Affine { scale: Expr, offset: Expr },
    /// `canonical = reference * base^(coeff * value)`
    Log {
        base: Expr,
        coeff: Expr,
        reference: Option<Expr>,
    },
    /// `canonical = reference * atan(value / coeff)`
    Tan {
        coeff: Expr,
        reference: Option<Expr>,
    },
}

#[derive(Clone, Copy)]
enum Family {
    Linear,
    Affine,
    Log,
    Tan,
}

/// Parse the single `#[linear|affine|log|tan(...)]` attribute on a unit variant.
fn parse_unit_spec(variant: &syn::Variant) -> syn::Result<UnitSpec> {
    let mut found: Option<UnitSpec> = None;
    for attr in &variant.attrs {
        let path = attr.path();
        let family = if path.is_ident("linear") {
            Family::Linear
        } else if path.is_ident("affine") {
            Family::Affine
        } else if path.is_ident("log") {
            Family::Log
        } else if path.is_ident("tan") {
            Family::Tan
        } else {
            continue;
        };
        if found.is_some() {
            return Err(syn::Error::new_spanned(
                attr,
                "a unit variant may carry only one of #[linear], #[affine], #[log], #[tan]",
            ));
        }
        let (positional, keyword) = attr.parse_args_with(parse_unit_args)?;
        found = Some(build_unit_spec(family, attr, positional, keyword)?);
    }
    found.ok_or_else(|| {
        syn::Error::new_spanned(
            &variant.ident,
            "missing #[linear], #[affine], #[log], or #[tan] on variant",
        )
    })
}

/// Collect an attribute's arguments into positional and `name = value` keyword
/// lists. Every argument is an expression (string literals included).
#[allow(clippy::type_complexity)]
fn parse_unit_args(input: ParseStream<'_>) -> syn::Result<(Vec<Expr>, Vec<(syn::Ident, Expr)>)> {
    let mut positional = Vec::new();
    let mut keyword = Vec::new();
    while !input.is_empty() {
        if input.peek(syn::Ident) && input.peek2(Token![=]) {
            let name: syn::Ident = input.parse()?;
            input.parse::<Token![=]>()?;
            keyword.push((name, input.parse()?));
        } else {
            positional.push(input.parse()?);
        }
        if input.is_empty() {
            break;
        }
        input.parse::<Token![,]>()?;
    }
    Ok((positional, keyword))
}

/// Assign collected args to the named slots (`short`, `long`, then the
/// family-specific numerics), positional first then by keyword.
fn build_unit_spec(
    family: Family,
    attr: &syn::Attribute,
    positional: Vec<Expr>,
    keyword: Vec<(syn::Ident, Expr)>,
) -> syn::Result<UnitSpec> {
    let names: &[&str] = match family {
        Family::Linear => &["short", "long", "scale"],
        Family::Affine => &["short", "long", "scale", "offset"],
        Family::Log => &["short", "long", "base", "coeff", "reference"],
        Family::Tan => &["short", "long", "coeff", "reference"],
    };

    let mut slots: Vec<Option<Expr>> = vec![None; names.len()];
    for (i, expr) in positional.into_iter().enumerate() {
        match slots.get_mut(i) {
            Some(slot) => *slot = Some(expr),
            None => {
                return Err(syn::Error::new_spanned(
                    &expr,
                    format!("too many positional arguments; expected {names:?}"),
                ));
            }
        }
    }
    for (name, value) in keyword {
        let key = name.to_string();
        match names.iter().position(|n| *n == key) {
            Some(i) if slots[i].is_none() => slots[i] = Some(value),
            Some(_) => {
                return Err(syn::Error::new_spanned(
                    &name,
                    format!("argument `{key}` given twice"),
                ));
            }
            None => {
                return Err(syn::Error::new_spanned(
                    &name,
                    format!("unknown argument `{key}`; expected one of {names:?}"),
                ));
            }
        }
    }

    let symbol = unit_str(take_req(&mut slots, 0, "short", attr)?)?;
    let long = unit_str(take_req(&mut slots, 1, "long", attr)?)?;
    let kind = match family {
        Family::Linear => UnitKind::Linear {
            scale: take_req(&mut slots, 2, "scale", attr)?,
        },
        Family::Affine => UnitKind::Affine {
            scale: take_req(&mut slots, 2, "scale", attr)?,
            offset: take_req(&mut slots, 3, "offset", attr)?,
        },
        Family::Log => UnitKind::Log {
            base: take_req(&mut slots, 2, "base", attr)?,
            coeff: take_req(&mut slots, 3, "coeff", attr)?,
            reference: slots[4].take(),
        },
        Family::Tan => UnitKind::Tan {
            coeff: take_req(&mut slots, 2, "coeff", attr)?,
            reference: slots[3].take(),
        },
    };
    Ok(UnitSpec { symbol, long, kind })
}

/// Take a required slot or error against the attribute span.
fn take_req(
    slots: &mut [Option<Expr>],
    index: usize,
    what: &str,
    attr: &syn::Attribute,
) -> syn::Result<Expr> {
    slots[index]
        .take()
        .ok_or_else(|| syn::Error::new_spanned(attr, format!("missing required argument `{what}`")))
}

/// Extract a string-literal value (for `short` / `long`).
fn unit_str(expr: Expr) -> syn::Result<String> {
    match expr {
        Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Str(s),
            ..
        }) => Ok(s.value()),
        other => Err(syn::Error::new_spanned(other, "expected a string literal")),
    }
}
